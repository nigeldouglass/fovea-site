#!/bin/sh
# Copies the app's help articles into help/articles.js, wrapped as a script so
# the support page can read them from GitHub Pages and from a local file:// open
# (browsers block fetch() on file://). Run it whenever the app's help changes.
set -e
cd "$(dirname "$0")"
SRC="${1:-../Fovea/Packages/Features/HelpFeature/Sources/HelpFeature/Resources/en.lproj/HelpArticles.json}"
{
  printf '// Generated by update-help.sh from the app'"'"'s HelpArticles.json. Do not edit.\n'
  printf 'window.FOVEA_HELP = '
  cat "$SRC"
  printf ';\n'
} > help/articles.js
echo "Wrote help/articles.js from $SRC"
